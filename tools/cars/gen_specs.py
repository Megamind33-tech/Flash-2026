"""Turn tools/cars/specs/*.json (written by export_car.py, Blender axes) into godot/scripts/vehicle/car_specs.gd.
Blender (x, y, z) with the car front at -Y maps to Godot (x, z, -y): +Z forward, +X left, +Y up."""
import json, glob, os

root = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(root, "..", "..", "godot", "scripts", "vehicle", "car_specs.gd")
g = lambda v: "Vector3(%.4f, %.4f, %.4f)" % (v[0], v[2], -v[1])
lines = ["## Generated by tools/cars/gen_specs.py from tools/cars/specs/*.json — do not edit by hand.",
         "## Wheel centres and body bounds in the car's Godot frame (+Z forward, +X left, tyre contact at y = 0).",
         "class_name CarSpecs", "extends RefCounted", "", "const GEOMETRY := {"]
for f in sorted(glob.glob(os.path.join(root, "specs", "*.json"))):
    d = json.load(open(f))
    w = d["wheels"]
    mn, mx = d["body_min"], d["body_max"]
    lines.append('\t"%s": {' % d["id"])
    for k in ("Wheel_FL", "Wheel_FR", "Wheel_RL", "Wheel_RR"):
        lines.append('\t\t"%s": [%s, %.4f, %.4f],' % (k, g(w[k]["centre"]), w[k]["radius"], w[k]["width"]))
    lines.append('\t\t"body_min": Vector3(%.3f, %.3f, %.3f), "body_max": Vector3(%.3f, %.3f, %.3f),'
                 % (mn[0], mn[2], -mx[1], mx[0], mx[2], -mn[1]))
    lines.append('\t\t"tris": %d,' % (d["body_tris"] + sum(v["tris"] for v in w.values())))
    lines.append("\t},")
lines.append("}")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out)
