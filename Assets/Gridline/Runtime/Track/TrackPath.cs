using UnityEngine;

namespace Gridline.Track
{
    /// <summary>
    /// Closed centreline of a circuit with distance queries, a precomputed racing line and an AI speed profile.
    /// Distance 0 is the start/finish line; the race runs in increasing distance.
    /// </summary>
    [DisallowMultipleComponent]
    public class TrackPath : MonoBehaviour
    {
        public string trackId = CircuitLayout.AshfordId;
        public string displayName = CircuitLayout.AshfordName;
        [Tooltip("Evenly spaced closed centreline points, generated by the track builder")]
        public Vector3[] points;
        public float halfWidth = CircuitLayout.AshfordHalfWidth;

        [Header("AI speed profile")]
        [Tooltip("Lateral grip used for corner speed, in g")]
        public float lateralGripG = 1.05f;
        public float maxSpeed = 62f;
        public float accel = 6f;
        public float decel = 9f;
        [Tooltip("Fraction of half width the racing line may use when cutting apexes")]
        [Range(0f, 0.9f)] public float racingLineUse = 0.55f;

        float[] cumulative;
        float[] speedProfile;
        float[] lineOffset;
        float length;
        bool ready;

        public float Length { get { EnsureReady(); return length; } }
        public int Count { get { return points == null ? 0 : points.Length; } }

        void Awake() { EnsureReady(); }

        public void Rebuild()
        {
            ready = false;
            EnsureReady();
        }

        void EnsureReady()
        {
            if (ready || points == null || points.Length < 4) return;
            int n = points.Length;
            cumulative = new float[n + 1];
            for (int i = 0; i < n; i++) cumulative[i + 1] = cumulative[i] + Vector3.Distance(points[i], points[(i + 1) % n]);
            length = cumulative[n];
            BuildRacingLine();
            BuildSpeedProfile();
            ready = true;
        }

        public float Wrap(float d)
        {
            float l = Length;
            d %= l;
            return d < 0f ? d + l : d;
        }

        int IndexAt(float d, out float t)
        {
            d = Wrap(d);
            int n = points.Length;
            int lo = 0, hi = n - 1;
            while (lo < hi)
            {
                int mid = (lo + hi + 1) >> 1;
                if (cumulative[mid] <= d) lo = mid; else hi = mid - 1;
            }
            float segLen = cumulative[lo + 1] - cumulative[lo];
            t = segLen > 1e-5f ? (d - cumulative[lo]) / segLen : 0f;
            return lo;
        }

        public Vector3 PositionAt(float d)
        {
            EnsureReady();
            int i = IndexAt(d, out float t);
            return Vector3.Lerp(points[i], points[(i + 1) % points.Length], t);
        }

        public Vector3 TangentAt(float d)
        {
            EnsureReady();
            int i = IndexAt(d, out _);
            Vector3 dir = points[(i + 1) % points.Length] - points[i];
            dir.y = 0f;
            return dir.sqrMagnitude > 1e-6f ? dir.normalized : Vector3.forward;
        }

        /// <summary>Unit vector pointing to the right of the driving direction.</summary>
        public Vector3 RightAt(float d)
        {
            Vector3 t = TangentAt(d);
            return new Vector3(t.z, 0f, -t.x);
        }

        public float RacingLineOffsetAt(float d)
        {
            EnsureReady();
            int i = IndexAt(d, out float t);
            return Mathf.Lerp(lineOffset[i], lineOffset[(i + 1) % points.Length], t);
        }

        public Vector3 RacingLinePointAt(float d)
        {
            return PositionAt(d) + RightAt(d) * RacingLineOffsetAt(d);
        }

        public float TargetSpeedAt(float d)
        {
            EnsureReady();
            int i = IndexAt(d, out float t);
            return Mathf.Lerp(speedProfile[i], speedProfile[(i + 1) % points.Length], t);
        }

        /// <summary>Projects a world position onto the centreline. Pass the previous segment as a hint for O(window) cost; -1 forces a full search.</summary>
        public float Project(Vector3 position, ref int segmentHint, out float lateral, int window = 24)
        {
            EnsureReady();
            int n = points.Length;
            int best = -1;
            float bestSqr = float.MaxValue, bestT = 0f;
            int start = segmentHint < 0 ? 0 : segmentHint - window;
            int end = segmentHint < 0 ? n - 1 : segmentHint + window;
            for (int k = start; k <= end; k++)
            {
                int i = ((k % n) + n) % n;
                Vector3 a = points[i], b = points[(i + 1) % n];
                Vector3 ab = b - a;
                ab.y = 0f;
                Vector3 ap = position - a;
                ap.y = 0f;
                float t = Mathf.Clamp01(Vector3.Dot(ap, ab) / Mathf.Max(1e-6f, ab.sqrMagnitude));
                float sqr = (ap - ab * t).sqrMagnitude;
                if (sqr < bestSqr)
                {
                    bestSqr = sqr;
                    best = i;
                    bestT = t;
                }
            }
            // A hinted search that lands far from the track (teleport, respawn) falls back to the full search once.
            if (segmentHint >= 0 && bestSqr > 40f * 40f)
            {
                segmentHint = -1;
                return Project(position, ref segmentHint, out lateral, window);
            }
            segmentHint = best;
            Vector3 p0 = points[best], p1 = points[(best + 1) % n];
            Vector3 dir = p1 - p0;
            dir.y = 0f;
            dir.Normalize();
            Vector3 right = new Vector3(dir.z, 0f, -dir.x);
            Vector3 closest = Vector3.Lerp(p0, p1, bestT);
            Vector3 offset = position - closest;
            offset.y = 0f;
            lateral = Vector3.Dot(offset, right);
            return cumulative[best] + bestT * (cumulative[best + 1] - cumulative[best]);
        }

        /// <summary>Signed curvature (1/m) at centreline point i, positive for right-hand bends.</summary>
        public float SignedCurvature(int i, int span = 5)
        {
            EnsureReady();
            return CurvatureAt(((i % points.Length) + points.Length) % points.Length, span);
        }

        /// <summary>Cumulative distance of centreline point i from the start line.</summary>
        public float DistanceOfPoint(int i)
        {
            EnsureReady();
            return cumulative[((i % points.Length) + points.Length) % points.Length];
        }

        /// <summary>Signed curvature (1/m) at point i, positive for right-hand bends, measured over a chord of +-span points to remove sampling noise.</summary>
        float CurvatureAt(int i, int span)
        {
            int n = points.Length;
            Vector3 a = points[((i - span) % n + n) % n], b = points[i], c = points[(i + span) % n];
            Vector2 ab = new Vector2(b.x - a.x, b.z - a.z), bc = new Vector2(c.x - b.x, c.z - b.z), ac = new Vector2(c.x - a.x, c.z - a.z);
            float cross = ab.x * bc.y - ab.y * bc.x;
            float denom = ab.magnitude * bc.magnitude * ac.magnitude;
            // Driving direction maps x->right as (t.z, -t.x); a clockwise (right) turn has negative 2D cross.
            return denom < 1e-6f ? 0f : -2f * cross / denom;
        }

        void BuildRacingLine()
        {
            int n = points.Length;
            var raw = new float[n];
            for (int i = 0; i < n; i++)
            {
                float k = CurvatureAt(i, 4);
                // Hug the inside of corners: positive curvature (right bend) -> move right.
                raw[i] = Mathf.Clamp(k * 220f, -1f, 1f) * halfWidth * racingLineUse;
            }
            // Wide symmetric smoothing spreads the apex shift into a natural out-in-out shape.
            lineOffset = Smooth(raw, 12, 2);
        }

        void BuildSpeedProfile()
        {
            int n = points.Length;
            var v = new float[n];
            float g = 9.81f;
            for (int i = 0; i < n; i++)
            {
                float k = Mathf.Abs(CurvatureAt(i, 5));
                float corner = k > 1e-4f ? Mathf.Sqrt(lateralGripG * g / k) : maxSpeed;
                v[i] = Mathf.Min(maxSpeed, corner);
            }
            v = Smooth(v, 2, 1);
            // Two laps of backward (braking) and forward (traction) passes so the closed loop converges.
            for (int pass = 0; pass < 2; pass++)
            {
                for (int k = 2 * n - 1; k >= 0; k--)
                {
                    int i = k % n, next = (i + 1) % n;
                    float ds = cumulative[i + 1] - cumulative[i];
                    v[i] = Mathf.Min(v[i], Mathf.Sqrt(v[next] * v[next] + 2f * decel * ds));
                }
                for (int k = 0; k < 2 * n; k++)
                {
                    int i = k % n, prev = (i - 1 + n) % n;
                    float ds = cumulative[prev + 1] - cumulative[prev];
                    v[i] = Mathf.Min(v[i], Mathf.Sqrt(v[prev] * v[prev] + 2f * accel * ds));
                }
            }
            speedProfile = v;
        }

        static float[] Smooth(float[] src, int radius, int iterations)
        {
            int n = src.Length;
            float[] a = (float[])src.Clone(), b = new float[n];
            for (int it = 0; it < iterations; it++)
            {
                for (int i = 0; i < n; i++)
                {
                    float sum = 0f;
                    for (int k = -radius; k <= radius; k++) sum += a[((i + k) % n + n) % n];
                    b[i] = sum / (2 * radius + 1);
                }
                var tmp = a; a = b; b = tmp;
            }
            return a;
        }

        void OnDrawGizmosSelected()
        {
            if (points == null || points.Length < 2) return;
            Gizmos.color = Color.cyan;
            for (int i = 0; i < points.Length; i++) Gizmos.DrawLine(points[i], points[(i + 1) % points.Length]);
        }
    }
}
